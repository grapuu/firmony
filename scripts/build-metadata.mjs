// Cloudflare supplies the commit only at build time, never as a runtime variable.
// https://developers.cloudflare.com/workers/ci-cd/builds/configuration/#default-variables
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const revisionOf = (value) => typeof value === 'string' && /^[a-f0-9]{40}$/i.test(value) ? value.toLowerCase() : null

export function buildMetadata(cloudflareRevision, gitRevision) {
  if (cloudflareRevision !== undefined) {
    const revision = revisionOf(cloudflareRevision)
    if (!revision) throw new Error('Neplatný identifikátor commitu v prostredí zostavenia.')
    return { revision, source: 'cloudflare' }
  }
  const revision = revisionOf(gitRevision)
  return { revision, source: revision ? 'git' : 'unknown' }
}

export async function generateBuildMetadata({ root = fileURLToPath(new URL('..', import.meta.url)), env = process.env } = {}) {
  let gitRevision
  if (env.WORKERS_CI_COMMIT_SHA === undefined) {
    try { gitRevision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() } catch { /* A source archive may have no Git checkout. */ }
  }
  // Only an allowlisted commit and its origin enter the bundle. No environment dump, dates, tokens or branch names.
  const metadata = buildMetadata(env.WORKERS_CI_COMMIT_SHA, gitRevision)
  const path = resolve(root, 'src/generated/deployment.ts')
  const contents = `// Generated by scripts/build-metadata.mjs.\nexport const BUILD_METADATA = ${JSON.stringify(metadata)} as const\n`
  try { if (await readFile(path, 'utf8') === contents) return metadata } catch { /* First build. */ }
  await mkdir(dirname(path), { recursive: true })
  const temporary = `${path}.${process.pid}.tmp`
  await writeFile(temporary, contents)
  await rename(temporary, path)
  return metadata
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generateBuildMetadata()
